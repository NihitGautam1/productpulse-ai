@dataclass
class Context:
    """Everything a page needs, already filtered to the sidebar selection."""
    reviews: pd.DataFrame          # filtered reviews with sentiment, language and risk columns
    mentions: pd.DataFrame         # theme mentions for those reviews
    priority: pd.DataFrame         # issue priority ranking
    spikes: dict                   # spike detection result
    subject: str                   # e.g. "Nimbus ANC Headphones" or "all products"
    source_label: str
    is_sample: bool
    date_label: str
    insights: list = field(default_factory=list)

    @property
    def selection_key(self) -> str:
        """Identifies the current selection so AI results are kept per selection."""
        ids = "|".join(self.reviews["review_id"].astype(str))
        return hashlib.sha1(f"{self.subject}|{ai_service.get_model_name()}|{ids}".encode()).hexdigest()

    def stats(self) -> str:
        monthly = theme_trends(self.mentions, "Monthly")
        if not monthly.empty:
            monthly = monthly.copy()
            monthly.index = monthly.index.strftime("%Y-%m")
        return build_stats_context(self.reviews, self.mentions, self.priority, self.spikes.get("alerts"), monthly)


PAGES: dict = {}  # filled in by app.py so pages can link to each other


# ---------------------------------------------------------------- shared helpers

def link(page: str, label: str, icon: str) -> None:
    """Link to another dashboard page (if navigation has been set up)."""
    if page in PAGES:
        st.page_link(PAGES[page], label=label, icon=icon)


def review_table(df: pd.DataFrame, extra: list[str] | None = None, order: list[str] | None = None) -> None:
    """Consistent, readable review table."""
    columns = order or ["review_id", "review_date", "product_name", "rating", "sentiment", "language",
                        "review_text"] + (extra or [])
    table = df[[c for c in columns if c in df.columns]].copy()
    st.dataframe(
        table, hide_index=True, width="stretch",
        column_config={
            "review_id": st.column_config.TextColumn("ID", width="small"),
            "review_date": st.column_config.DateColumn("Date", format="DD MMM YYYY", width="medium"),
            "product_name": st.column_config.TextColumn("Product"),
            "rating": st.column_config.NumberColumn("Rating", format="%d ★", width="small"),
            "sentiment": st.column_config.TextColumn("Sentiment", width="small"),
            "sentiment_score": st.column_config.NumberColumn("Score", format="%.2f", width="small"),
            "language": st.column_config.TextColumn("Language", width="small"),
            "review_text": st.column_config.TextColumn("Review", width="large"),
            "risk_level": st.column_config.TextColumn("Risk", width="small"),
            "risk_score": st.column_config.ProgressColumn("Risk score", min_value=0, max_value=100, format="%d"),
            "risk_reasons": st.column_config.ListColumn("Why flagged", width="large"),
            "themes": st.column_config.ListColumn("Themes"),
            "relevance": st.column_config.ProgressColumn("Relevance", min_value=0, max_value=1.5, format="%.2f"),
        },
    )


def show_ai_result(result: dict, reviews: pd.DataFrame) -> None:
    """Render an AI answer with its model note, citation check and the cited reviews as evidence."""
    st.markdown(result["text"])
    note = f"AI-generated by `{result['model']}` from {result['reviews_used']} reviews"
    if result["reviews_used"] < result["reviews_total"]:
        note += f" (most recent {result['reviews_used']} of {result['reviews_total']})"
    if result["chunks"] > 1:
        note += f", processed in {result['chunks']} batches"
    st.caption(note + ". Verify important points against the evidence below.")
    if result["unknown_ids"]:
        st.warning("The AI cited review ID(s) that are not in this selection: " + ", ".join(result["unknown_ids"])
                   + ". Treat the related statements with caution.")
    cited = reviews[reviews["review_id"].astype(str).isin(result["cited_ids"])]
    with st.expander(f"Evidence · {len(cited)} cited review(s), checked against the data"):
        if cited.empty:
            st.write("No reviews were cited.")
        else:
            review_table(cited)


def ai_unavailable_note() -> None:
    st.info(ai_service.NOT_CONFIGURED_MESSAGE + " The sections below are computed directly from the data.", icon="🔑")


def theme_quotes(ctx: Context, theme: str, polarity: str, limit: int = 2) -> None:
    for _, row in evidence_for_theme(ctx.mentions, theme, polarity, limit).iterrows():
        styles.quote(row, highlight=row["clause"])


