def trends(ctx: Context) -> None:
    styles.page_header("Issues", "Trends & Alerts", "How feedback changes over time, and unusual recent spikes.",
                       [ctx.subject, ctx.date_label])
    df = ctx.reviews
    if df.empty:
        st.warning("No reviews match the current filters.")
        return

    styles.section("Spike alerts", "Detected patterns, not confirmed causes. Recent window vs the weeks before it.")
    spikes = ctx.spikes
    if spikes["status"] != "ok":
        st.info(spikes["message"], icon="ℹ️")
    elif not spikes["alerts"]:
        st.success("No unusual spikes detected. " + spikes["message"], icon="✅")
    else:
        st.caption(spikes["message"])
        cols = st.columns(2)
        for i, alert in enumerate(spikes["alerts"]):
            with cols[i % 2]:
                styles.alert_card(alert)

    auto = auto_frequency(df)
    choice = st.segmented_control("Group by", ["Auto", "Daily", "Weekly", "Monthly"], default="Auto",
                                  key="trend_frequency")
    frequency = auto if choice in (None, "Auto") else choice
    trend = review_trends(df, frequency)
    st.caption(f"Grouped {frequency.lower()}.")

    left, right = st.columns(2, gap="large")
    with left:
        with st.container(border=True):
            styles.section("Review volume by sentiment")
            st.plotly_chart(charts.sentiment_volume(trend), config={"displayModeBar": False})
        with st.container(border=True):
            styles.section("Negative reviews (% of period)")
            st.plotly_chart(charts.line_chart(trend, "negative_pct", "Negative %", charts.SENTIMENT_COLORS["Negative"],
                                              [0, 100], "%"), config={"displayModeBar": False})
    with right:
        with st.container(border=True):
            styles.section("Average rating")
            st.plotly_chart(charts.line_chart(trend, "avg_rating", "Average rating", "#2a78d6", [1, 5.2]),
                            config={"displayModeBar": False})
        with st.container(border=True):
            # One level coarser than the other charts: five theme lines per week are too noisy to read.
            theme_frequency = {"Daily": "Weekly", "Weekly": "Monthly", "Monthly": "Monthly"}[frequency]
            styles.section("Complaint themes over time",
                           f"Top 5 themes by complaint volume, grouped {theme_frequency.lower()} for readability.")
            themes_over_time = theme_trends(ctx.mentions, theme_frequency)
            if themes_over_time.empty:
                st.write("No complaints in this selection.")
            else:
                st.plotly_chart(charts.theme_trend_lines(themes_over_time), config={"displayModeBar": False})

    with st.expander("Trend data table"):
        st.dataframe(trend, hide_index=True, width="stretch")


