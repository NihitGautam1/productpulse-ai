def integrity(ctx: Context) -> None:
    styles.page_header("Trust", "Review Integrity", "Potentially suspicious reviews, with the reasons they were flagged.",
                       [ctx.subject, f"{len(ctx.reviews)} reviews"])
    df = ctx.reviews
    st.warning(f"**{RISK_DISCLAIMER}** Signals such as duplicate text or review bursts can have innocent explanations. "
               "Use this list to decide what to look at more closely, never to accuse customers.", icon="⚠️")
    if df.empty:
        return

    levels = df["risk_level"].value_counts()
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("High risk", int(levels.get("High", 0)), border=True)
    c2.metric("Medium risk", int(levels.get("Medium", 0)), border=True)
    c3.metric("Low risk", int(levels.get("Low", 0)), border=True)
    c4.metric("Near-duplicates", int((df["max_similarity"] >= 0.9).sum()), border=True,
              help="Reviews of similar length with at least 90% text similarity to another review.")

    left, right = st.columns((1, 1.4), gap="large")
    with left:
        with st.container(border=True):
            styles.section("Risk levels")
            st.plotly_chart(charts.risk_levels(df), config={"displayModeBar": False})
    with right:
        with st.container(border=True):
            styles.section("How the risk score works", "Points add up per review (capped at 100).")
            st.markdown("""
| Signal | Points |
|---|---|
| Near-duplicate text (≥ 90% similar) | +40 |
| Very similar text (≥ 75% similar) | +20 |
| Burst of same-rating reviews on one day | +20 |
| Generic text, no product detail | +15 |
| Star rating contradicts text | +15 |
| Promotional phrasing | +10 |
| Excessive "!!!" or capitals | +10 |
| Extreme rating with another signal | +5 |

**High** ≥ 55 · **Medium** ≥ 30 · **Low** < 30
""")

    styles.section("Flagged reviews", "Each row lists every signal that contributed to its score.")
    level_filter = st.pills("Show", ["High", "Medium", "Low"], default=["High", "Medium"], selection_mode="multi",
                            key="risk_filter")
    flagged = df[df["risk_level"].isin(level_filter or [])].sort_values("risk_score", ascending=False)
    st.caption(f"{len(flagged)} review(s)")
    columns = ["review_id", "risk_level", "risk_score", "risk_reasons", "review_text", "rating",
               "review_date", "product_name"]
    review_table(flagged[columns], extra=["risk_level", "risk_score", "risk_reasons"], order=columns)


# ---------------------------------------------------------------- Review Explorer

def explorer(ctx: Context) -> None:
    styles.page_header("Data", "Review Explorer", "Search and filter every review with its analysis.",
                       [ctx.subject, f"{len(ctx.reviews)} reviews"])
    df = ctx.reviews.copy()
    if df.empty:
        st.warning("No reviews match the current filters.")
        return
    theme_lists = ctx.mentions.assign(label=ctx.mentions["theme"] + " (" + ctx.mentions["polarity"] + ")") \
        .groupby("review_id")["label"].apply(list)
    df["themes"] = df["review_id"].map(theme_lists).apply(lambda v: v if isinstance(v, list) else [])

    c1, c2, c3, c4 = st.columns((2.2, 1, 1, 1))
    query = c1.text_input("Search", placeholder="Words, product or review ID, e.g. battery, delivery, D012")
    sentiments = c2.multiselect("Sentiment", ["Positive", "Neutral", "Negative"])
    languages = c3.multiselect("Language", ["English", "Hinglish", "Hindi"])
    risks = c4.multiselect("Risk", ["High", "Medium", "Low"])
    c5, c6 = st.columns((1, 2.2))
    ratings = c5.slider("Rating", 1, 5, (1, 5))
    theme_filter = c6.multiselect("Theme", sorted(ctx.mentions["theme"].unique()))

    view = df[(df["rating"] >= ratings[0]) & (df["rating"] <= ratings[1])]
    if query.strip():
        q = query.strip()
        view = view[view["review_text"].str.contains(q, case=False, regex=False)
                    | view["product_name"].str.contains(q, case=False, regex=False)
                    | view["review_id"].astype(str).str.contains(q, case=False, regex=False)]
    if sentiments:
        view = view[view["sentiment"].isin(sentiments)]
    if languages:
        view = view[view["language"].isin(languages)]
    if risks:
        view = view[view["risk_level"].isin(risks)]
    if theme_filter:
        ids = ctx.mentions.loc[ctx.mentions["theme"].isin(theme_filter), "review_id"]
        view = view[view["review_id"].isin(ids)]

    top_left, top_right = st.columns((3, 1))
    top_left.caption(f"{len(view)} of {len(df)} reviews")
    export = view.drop(columns=["risk_reasons", "themes"]).assign(
        themes=view["themes"].str.join("; "), risk_reasons=view["risk_reasons"].str.join("; "))
    top_right.download_button("Download CSV", export.to_csv(index=False).encode("utf-8"),
                              "productpulse_reviews.csv", "text/csv", width="stretch")
    review_table(view.sort_values("review_date", ascending=False),
                 extra=["sentiment_score", "themes", "risk_level"])

    with st.container(border=True):
        styles.section("Languages", "Detected with a script + vocabulary heuristic.")
        st.plotly_chart(charts.language_mix(df), config={"displayModeBar": False})


