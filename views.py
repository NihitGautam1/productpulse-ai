SUGGESTED_QUESTIONS = [
    "What are the biggest complaints?",
    "What do customers like most?",
    "Why are customers giving low ratings?",
    "Are delivery complaints increasing?",
    "What should the company improve first?",
]


def ask(ctx: Context) -> None:
    styles.page_header("AI analysis", "Ask Your Reviews",
                       "Ask a question in plain English. Answers use only your reviews and computed statistics.",
                       [ctx.subject, f"{len(ctx.reviews)} reviews"])
    if ctx.reviews.empty:
        st.warning("No reviews match the current filters.")
        return
    if not ai_service.is_ai_configured():
        st.info("AI answers need AI_API_KEY. Without it, you will see the most relevant reviews and statistics "
                "for your question instead.", icon="🔑")

    history = st.session_state.setdefault("qa_history", {}).setdefault(ctx.selection_key, [])
    picked = st.pills("Try a question", SUGGESTED_QUESTIONS, key=f"pill_{ctx.selection_key[:8]}_{len(history)}")
    typed = st.chat_input("Ask about your reviews, e.g. “Is battery life a common problem?”")
    question = typed or picked

    for item in history:
        render_qa(item, ctx)
    if question:
        item = answer(ctx, question)
        history.append(item)
        render_qa(item, ctx)
    if history and st.button("Clear conversation", type="tertiary"):
        history.clear()
        st.rerun()


def answer(ctx: Context, question: str) -> dict:
    relevant = find_relevant_reviews(ctx.reviews, question, ctx.mentions, limit=60)
    item = {"question": question, "relevant_ids": relevant["review_id"].astype(str).tolist(), "result": None, "error": None}
    if ai_service.is_ai_configured():
        with st.spinner("Searching reviews and writing an answer..."):
            try:
                item["result"] = ai_service.answer_question(question, relevant, ctx.stats(), ctx.subject)
            except ai_service.AIServiceError as exc:
                item["error"] = str(exc)
    return item


def render_qa(item: dict, ctx: Context) -> None:
    with st.chat_message("user"):
        st.write(item["question"])
    with st.chat_message("assistant", avatar="✨"):
        if item["result"]:
            show_ai_result(item["result"], ctx.reviews)
            return
        if item["error"]:
            st.error(item["error"])
        relevant = ctx.reviews[ctx.reviews["review_id"].astype(str).isin(item["relevant_ids"][:8])]
        st.markdown("**Most relevant reviews** (found by text search; no AI used):")
        for _, row in relevant.iterrows():
            styles.quote(row)
        with st.expander("Statistics for this selection"):
            st.code(ctx.stats(), language=None)


