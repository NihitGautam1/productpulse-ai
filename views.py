def priority(ctx: Context) -> None:
    styles.page_header("Issues", "Priority Issues",
                       "Which problems matter most, why, and the real reviews behind each one.",
                       [ctx.subject, f"{len(ctx.reviews)} reviews"])
    if ctx.priority.empty:
        st.success("No complaints detected in this selection.")
        return
    with st.expander("How the priority score works"):
        st.markdown(
            f"""
**Priority score (0-100)** = {WEIGHTS['frequency']} × frequency + {WEIGHTS['negativity']} × negativity
+ {WEIGHTS['low_ratings']} × low ratings + {WEIGHTS['recent_rise']} × recent rise

- **Frequency**: share of all reviews complaining about the issue (20% or more = full marks)
- **Negativity**: how negative the complaint sentences are (average VADER score)
- **Low ratings**: share of those complaint reviews rated 1-2 stars
- **Recent rise**: 1 if the complaint rate rose 50%+ recently, 0.5 if it rose, 0 otherwise

Levels need both a score **and** enough evidence, so one complaint is never Critical:
**Critical** ≥ 70 and ≥ 5 reviews · **High** ≥ 50 and ≥ 3 · **Medium** ≥ 30 and ≥ 2 · otherwise **Low**.
"""
        )

    left, right = st.columns((1, 1), gap="large")
    with left:
        with st.container(border=True):
            styles.section("Priority ranking")
            st.plotly_chart(charts.priority_scores(ctx.priority), config={"displayModeBar": False})
    with right:
        with st.container(border=True):
            styles.section("Praise vs complaints by theme", "Number of reviews praising (right) or complaining (left).")
            st.plotly_chart(charts.praise_vs_complaints(theme_summary(ctx.mentions, len(ctx.reviews))),
                            config={"displayModeBar": False})

    table = ctx.priority[["theme", "level", "score", "complaint_reviews", "share_pct", "avg_rating",
                          "recent_rate_pct", "earlier_rate_pct"]]
    st.dataframe(table, hide_index=True, width="stretch", column_config={
        "theme": "Issue", "level": "Priority",
        "score": st.column_config.ProgressColumn("Score", min_value=0, max_value=100, format="%.0f"),
        "complaint_reviews": st.column_config.NumberColumn("Complaint reviews"),
        "share_pct": st.column_config.NumberColumn("% of all reviews", format="%.1f%%"),
        "avg_rating": st.column_config.NumberColumn("Avg rating", format="%.2f ★"),
        "recent_rate_pct": st.column_config.NumberColumn("Recent rate", format="%.1f%%"),
        "earlier_rate_pct": st.column_config.NumberColumn("Earlier rate", format="%.1f%%"),
    })

    styles.section("Evidence by issue", "Real reviews supporting each issue. The highlighted text is what was detected.")
    for row in ctx.priority.itertuples():
        title = f"{row.theme} · {row.level} priority · {row.complaint_reviews} review(s)"
        with st.expander(title, expanded=row.level in ("Critical", "High") and row.Index < 2):
            st.caption(f"Score {row.score} = frequency {row.frequency} · negativity {row.negativity} · "
                       f"low ratings {row.low_ratings} · recent rise {row.recent_rise}")
            if row.complaint_reviews == 1:
                st.caption("Isolated: only one review mentions this, so it is not yet a recurring pattern.")
            theme_quotes(ctx, row.theme, "complaint", 3)
            all_rows = ctx.reviews[ctx.reviews["review_id"].isin(
                ctx.mentions.loc[(ctx.mentions["theme"] == row.theme) & (ctx.mentions["polarity"] == "complaint"), "review_id"])]
            if len(all_rows) > 3 and st.toggle(f"Show all {len(all_rows)} reviews", key=f"all_{row.theme}"):
                review_table(all_rows.sort_values("review_date", ascending=False))


