def overview(ctx: Context) -> None:
    df = ctx.reviews
    styles.page_header("Dashboard overview", ctx.subject if ctx.subject != "all products" else "All products",
                       "How customers feel, what they complain about, and what to fix first.",
                       [ctx.date_label, f"{len(df)} reviews", ctx.source_label])
    if df.empty:
        st.warning("No reviews match the current filters.")
        return

    counts = sentiment_counts(df)
    total = len(df)
    # Small trend lines inside the KPI cards (weekly or monthly, depending on the date span).
    trend = review_trends(df, "Monthly" if auto_frequency(df) == "Monthly" else "Weekly")
    trend = trend[trend["reviews"] > 0]
    spark = dict(chart_type="line") if len(trend) >= 3 else {}
    positive_pct = (trend["positive"] / trend["reviews"] * 100).round(1).tolist()

    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Reviews analysed", f"{total:,}", border=True,
              **(dict(spark, chart_data=trend["reviews"].tolist(), chart_type="bar") if spark else {}))
    c2.metric("Average rating", f"{df['rating'].mean():.2f} ★", border=True,
              **(dict(spark, chart_data=trend["avg_rating"].tolist()) if spark else {}))
    c3.metric("Positive", f"{counts['Positive'] / total:.0%}", f"{counts['Positive']} reviews",
              delta_color="off", delta_arrow="off", border=True,
              **(dict(spark, chart_data=positive_pct) if spark else {}))
    c4.metric("Negative", f"{counts['Negative'] / total:.0%}", f"{counts['Negative']} reviews",
              delta_color="off", delta_arrow="off", border=True,
              **(dict(spark, chart_data=trend["negative_pct"].tolist()) if spark else {}))
    c5.metric("Health score", f"{health_score(df)}/100", border=True,
              help="50% average rating (scaled 1-5 → 0-1) + 50% net sentiment ((positive − negative) share, scaled to 0-1).")
    if spark:
        st.caption("Mini charts show each metric over time for the selected dates.")

    alerts = ctx.spikes.get("alerts", [])
    if alerts:
        st.space("small")
        cols = st.columns(min(len(alerts), 3))
        for col, alert in zip(cols, alerts[:3]):
            with col:
                styles.alert_card(alert)
        link("trends", label=f"See all {len(alerts)} alert(s) and trends", icon="📈")

    st.space("small")
    left, right = st.columns((1, 1.15), gap="large")
    with left:
        with st.container(border=True):
            styles.section("How customers feel", "VADER sentiment of every review (Hinglish/Hindi supported).")
            st.plotly_chart(charts.sentiment_bars(counts), config={"displayModeBar": False})
            styles.section("Star ratings")
            st.plotly_chart(charts.rating_distribution(df), config={"displayModeBar": False})
    with right:
        with st.container(border=True):
            styles.section("Most important problems", "Ranked by the transparent priority score.")
            if ctx.priority.empty:
                st.write("No complaints detected in this selection.")
            else:
                rows = "".join(
                    styles.issue_row(r.theme, r.level, f"{r.complaint_reviews} complaint reviews · {r.share_pct}% of all · avg {r.avg_rating}★",
                                     charts.LEVEL_COLORS[r.level])
                    for r in ctx.priority.head(5).itertuples()
                )
                styles.html_block(rows)
                top = ctx.priority.iloc[0]
                st.markdown(f"**Example: {top.theme}**")
                theme_quotes(ctx, top.theme, "complaint", 2)
                link("priority", label="Full priority ranking and evidence", icon="🎯")

    left, right = st.columns(2, gap="large")
    with left:
        with st.container(border=True):
            styles.section("What customers love", "Themes most often praised.")
            summary = theme_summary(ctx.mentions, total)
            praised = summary[summary["praise"] >= 2].sort_values("praise", ascending=False).head(3)
            if praised.empty:
                st.write("No recurring praise found.")
            for row in praised.itertuples():
                st.markdown(f"**{row.theme}** · {row.praise} reviews ({row.praise_pct}%)")
                theme_quotes(ctx, row.theme, "praise", 1)
    with right:
        with st.container(border=True):
            styles.section("Key insights", "Computed from the data, each backed by review IDs.")
            for item in [i for i in ctx.insights if i["kind"] != "overview"][:4]:
                styles.insight_card(item["text"], item["kind"], item["evidence"])
            link("ai", label="AI summary & recommendations", icon="✨")

    with st.container(border=True):
        styles.section("AI summary", "Generated from the reviews in this selection.")
        overall_ai_block(ctx, compact=True)


def overall_ai_block(ctx: Context, compact: bool = False) -> None:
    """Overall AI summary with a generate button; shared by Overview and AI Insights."""
    if not ai_service.is_ai_configured():
        st.info(ai_service.NOT_CONFIGURED_MESSAGE, icon="🔑")
        return
    store = st.session_state.setdefault("ai_results", {})
    key = (ctx.selection_key, "overall")
    if key not in store:
        if st.button("Generate AI summary", type="primary", key=f"gen_overall_{compact}"):
            with st.spinner("Reading reviews and writing the summary..."):
                try:
                    store[key] = ai_service.generate_review_summary(ctx.reviews, ctx.subject)
                except ai_service.AIServiceError as exc:
                    st.error(str(exc))
    if key in store:
        show_ai_result(store[key], ctx.reviews)


# ---------------------------------------------------------------- AI Insights

AI_TASKS = {
    "overall": ("Overall Summary", lambda ctx: ai_service.generate_review_summary(ctx.reviews, ctx.subject)),
    "positive": ("Positive Feedback", lambda ctx: ai_service.generate_positive_summary(
        ctx.reviews[ctx.reviews["sentiment"] == "Positive"], ctx.subject)),
    "negative": ("Negative Feedback", lambda ctx: ai_service.generate_negative_summary(
        ctx.reviews[ctx.reviews["sentiment"] == "Negative"], ctx.subject)),
    "insights": ("Insights & Actions", lambda ctx: ai_service.generate_key_insights(ctx.reviews, ctx.subject, ctx.stats())),
}


def run_ai_tasks(ctx: Context, names: list[str]) -> dict[str, str]:
    """Run several AI tasks in parallel threads. Returns {task: error message} for failures."""
    store = st.session_state.setdefault("ai_results", {})
    errors: dict[str, str] = {}
    with ThreadPoolExecutor(max_workers=4) as pool:
        futures = {name: pool.submit(AI_TASKS[name][1], ctx) for name in names}
        for name, future in futures.items():
            try:
                store[(ctx.selection_key, name)] = future.result()
            except ai_service.AIServiceError as exc:
                errors[name] = str(exc)
    return errors


def ai_insights(ctx: Context) -> None:
    styles.page_header("AI analysis", "AI Review Insights",
                       "Summaries, praise, complaints and recommended actions, every point citing real reviews.",
                       [ctx.subject, f"{len(ctx.reviews)} reviews", f"Model: {ai_service.get_model_name()}"])
    if ctx.reviews.empty:
        st.warning("No reviews match the current filters.")
        return
    configured = ai_service.is_ai_configured()
    store = st.session_state.setdefault("ai_results", {})
    missing = [n for n in AI_TASKS if (ctx.selection_key, n) not in store]

    if not configured:
        ai_unavailable_note()
    elif missing:
        if st.button("✨ Generate full AI analysis", type="primary"):
            with st.status("Analysing reviews with AI...", expanded=False) as status:
                errors = run_ai_tasks(ctx, missing)
                if errors:
                    status.update(label="Some AI sections failed", state="error")
                    for name, message in errors.items():
                        st.error(f"{AI_TASKS[name][0]}: {message}")
                else:
                    status.update(label="AI analysis complete", state="complete")
        st.caption("Runs four grounded AI requests in parallel: overall summary, positive feedback, negative feedback, insights & actions.")

    tabs = st.tabs([AI_TASKS[n][0] for n in AI_TASKS])
    for tab, name in zip(tabs, AI_TASKS):
        with tab:
            result = store.get((ctx.selection_key, name))
            if result:
                show_ai_result(result, ctx.reviews)
            elif configured:
                st.caption("Not generated yet. Use the button above.")
            computed_fallback(ctx, name)


def computed_fallback(ctx: Context, name: str) -> None:
    """Data-driven content shown under each AI tab (and instead of it when AI is off)."""
    total = len(ctx.reviews)
    summary = theme_summary(ctx.mentions, total)
    st.divider()
    if name == "overall":
        styles.section("Computed overview")
        for item in ctx.insights[:1]:
            styles.insight_card(item["text"], item["kind"])
    elif name in ("positive", "negative"):
        polarity, column = ("praise", "praise") if name == "positive" else ("complaint", "complaints")
        styles.section("Most mentioned " + ("strengths" if name == "positive" else "problems"),
                       "Computed from theme detection, with real review quotes.")
        top = summary[summary[column] > 0].sort_values(column, ascending=False).head(4)
        if top.empty:
            st.write("Nothing found in this selection.")
        for row in top.itertuples():
            st.markdown(f"**{row.theme}** · {getattr(row, column)} reviews")
            theme_quotes(ctx, row.theme, polarity, 2)
    else:
        styles.section("Computed insights", "Calculated directly from the data, each with evidence review IDs.")
        for item in ctx.insights:
            styles.insight_card(item["text"], item["kind"], item["evidence"])


